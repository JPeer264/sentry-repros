import * as Sentry from '@sentry/node';
import * as dc from 'node:diagnostics_channel';
Sentry.init({ dsn: 'https://public@example.invalid/1', tracesSampleRate: 1.0, tunnel: process.env.SENTRY_TUNNEL });
console.log('after init:', dc.tracingChannel('mysql2:query').start.hasSubscribers);
if (process.env.GC === '1' && globalThis.Bun) Bun.gc(true);
console.log('after explicit gc:', dc.tracingChannel('mysql2:query').start.hasSubscribers);
const mysql = (await import('mysql2/promise')).default;
const pool = mysql.createPool({ host: '127.0.0.1', port: 3307, user: 'root', database: 'app', connectionLimit: 2 });
await Sentry.startSpan({ name: 'gcprobe', op: 'test' }, async () => { await pool.query('SELECT 1'); });
console.log('at query time:', dc.tracingChannel('mysql2:query').start.hasSubscribers);
await Sentry.flush(2000); await pool.end(); process.exit(0);
